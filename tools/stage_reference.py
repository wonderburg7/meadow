"""Regenerate docs/challenge-stages.md from scripts/challenge_stages.gd.

Dave, 8 Sep 2026: "when talking about stages in particular challenges, say
what the stage is, or point me to where the stage details are." A check or a
plan that names "2.1" is unreadable on its own, and the stage data lives in a
GDScript const array nobody should have to read to answer "what is 2.1?".

This walks STAGES_1/STAGES_2 with a small brace-matching scan rather than a
GDScript parser: the arrays are plain dictionary literals and only three
fields are needed. Run it after any edit to those arrays:

    python tools/stage_reference.py

It rewrites docs/challenge-stages.md in place and exits non-zero if the
generated text differs from what is on disk when --check is passed, which is
how tools/verify.ps1 keeps the two in step.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "scripts" / "challenge_stages.gd"
TARGET = ROOT / "docs" / "challenge-stages.md"

FIELD = re.compile(r'"(id|goal|goal_text|instruction)"\s*:\s*"([^"]*)"')


def _array_body(text: str, name: str) -> str:
    """The text between `const <name> := [` and its matching `]`."""
    start = text.index(f"const {name} := [")
    open_bracket = text.index("[", start)
    depth = 0
    for index in range(open_bracket, len(text)):
        char = text[index]
        if char == "[":
            depth += 1
        elif char == "]":
            depth -= 1
            if depth == 0:
                return text[open_bracket + 1 : index]
    raise ValueError(f"{name}: unbalanced brackets")


def _stages(body: str) -> list[dict[str, str]]:
    """One record per top-level `{...}` in the array body."""
    stages: list[dict[str, str]] = []
    depth = 0
    start = -1
    for index, char in enumerate(body):
        if char == "{":
            if depth == 0:
                start = index
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                chunk = body[start : index + 1]
                # First occurrence wins: a stage record's own "id" comes
                # before the nested prompt records', which reuse the key.
                fields: dict[str, str] = {}
                for key, value in FIELD.findall(chunk):
                    fields.setdefault(key, value)
                if "id" in fields:
                    stages.append(fields)
    return stages


def _table(stages: list[dict[str, str]]) -> list[str]:
    lines = [
        "| Stage | Goal, as the player sees it | Internal goal check | What the player does |",
        "| --- | --- | --- | --- |",
    ]
    for stage in stages:
        goal_text = stage.get("goal_text", "").replace("Goal: ", "").strip()
        instruction = stage.get("instruction", "").strip() or "--"
        lines.append(
            "| `%s` | %s | `%s` | %s |"
            % (stage["id"], goal_text or "--", stage.get("goal", "--"), instruction)
        )
    return lines


def render(source: Path = SOURCE) -> str:
    text = source.read_text(encoding="utf-8")
    lines = [
        "# Challenge stages — what each id means",
        "",
        "<!-- CONTEXT: reference | LAYER: on-demand -->",
        "Status: generated | Owner: tools/stage_reference.py | Verified: on every run of tools/verify.ps1",
        "",
        "**Do not edit this file by hand.** It is generated from",
        "`scripts/challenge_stages.gd` by `python tools/stage_reference.py`, which",
        "`tools/verify.ps1` re-runs with `--check` so the two cannot drift.",
        "",
        "**Why it exists.** Any check, plan or session note that names a stage id",
        "must either say what happens at that stage in the same sentence, or link",
        "here (Dave, 8 Sep 2026). \"C-5 needs a run past 2.1\" tells a reader",
        "nothing; \"past 2.1, where the nectar stores fall and recover\" does.",
        "",
        "## Challenge 1 — the founding queen",
        "",
    ]
    lines += _table(_stages(_array_body(text, "STAGES_1")))
    lines += [
        "",
        "## Challenge 2 — the foraging pipeline",
        "",
    ]
    lines += _table(_stages(_array_body(text, "STAGES_2")))
    lines += [
        "",
        "## Where the rest of a stage lives",
        "",
        "Dr Gallerin's per-stage prompt lines, the `unlocked_keys` each stage",
        "opens up and the delays those prompts fire on are all in the same",
        "records in `scripts/challenge_stages.gd`; only the four columns above are",
        "reproduced here, because they are the ones a reader needs to know which",
        "stage is being talked about.",
        "",
        "Challenge 2's rescue and failure thresholds (`C2_RESCUE_THRESHOLD`,",
        "`C2_RESCUE_AMOUNT`, `C2_FAILURE_FLOOR`) are constants in the same file,",
        "and the branch that reads them is",
        "`scripts/challenge_runner.gd::_check_c2_failure`.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    rendered = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != rendered:
            print(
                "docs/challenge-stages.md is out of date -- run "
                "`python tools/stage_reference.py`",
                file=sys.stderr,
            )
            return 1
        return 0
    before = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if before == rendered:
        print(f"unchanged {TARGET.relative_to(ROOT)}")
        return 0
    TARGET.write_text(rendered, encoding="utf-8")
    print(f"regenerated {TARGET.relative_to(ROOT)} (was stale)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
